// pack-manifest.mjs — Black 2 baseline imposition (docs/black2-baseline.md).
// B2-R1/R2: every system module and data pack is registered; the legacy
// monoliths are frozen at their caps in pack-manifest.caps.json — growth
// fails this gate (exit 1). Regenerates docs/pack-manifest.md.
// Zero-dependency, Node stdlib only (repo rule).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const caps = JSON.parse(fs.readFileSync(path.join(root, 'scripts/pack-manifest.caps.json'), 'utf8'));

function scan(dir, role) {
  const out = [];
  for (const name of fs.readdirSync(path.join(root, dir)).sort()) {
    const p = path.join(root, dir, name);
    if (!fs.statSync(p).isFile()) continue;
    const text = fs.readFileSync(p, 'utf8');
    out.push({ file: `${dir}/${name}`, bytes: Buffer.byteLength(text), lines: text.split('\n').length - 1, role });
  }
  return out;
}

const core = scan('src/engine', 'core (thin — B2-R1)');
const systems = scan('src/game', 'system module (overlay analogue — B2-R1)');
const packs = scan('src/data', 'content pack (NARC analogue — B2-R2)');
const save = scan('src/save', 'save subsystem');
const audioDir = path.join(root, 'audio');
const audioBytes = fs.readdirSync(audioDir).reduce((n, f) => n + fs.statSync(path.join(audioDir, f)).size, 0);

let fail = 0;
const rows = [];
for (const section of [core, systems, packs, save]) {
  for (const e of section) {
    const cap = caps.frozen[e.file];
    let note = '';
    if (cap !== undefined) {
      if (e.lines > cap) { note = ` ❌ FROZEN — ${e.lines} lines > cap ${cap} (B2-R1)`; fail = 1; }
      else note = ` (frozen, cap ${cap})`;
    }
    rows.push(`| ${e.file} | ${e.bytes} | ${e.lines} | ${e.role}${note} |`);
  }
}

const md = `# Pack Manifest — generated by scripts/pack-manifest.mjs, do not hand-edit
Black 2 baseline registry (docs/black2-baseline.md): our overlay table + NARC index, in web form.
Totals 2026-11-11 baseline: ARM9-analogue core ${core.reduce((n, e) => n + e.bytes, 0)} B ·
system modules ${systems.length} · content packs ${packs.length} ·
audio subsystem (B2-R3) ${audioBytes} B in audio/ + src/engine/audio.mjs.

| File | Bytes | Lines | Role |
|---|---|---|---|
${rows.join('\n')}
`;
fs.writeFileSync(path.join(root, 'docs/pack-manifest.md'), md);
console.log(`pack-manifest: ${core.length} core, ${systems.length} systems, ${packs.length} packs, audio ${audioBytes} B — ${fail ? 'GATE FAILED' : 'gate PASS'}`);
process.exit(fail);
