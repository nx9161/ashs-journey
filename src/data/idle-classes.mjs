// Motion parameters per class (battle.mjs idleMotion consumes these —
// amplitude in logical px, periods in ms). No two classes share both
// amplitude and rate on either axis.
export const IDLE_CLASS_PARAMS = {
  grounded:   { ampY: 1.6, periodY: 2400, ampX: 0,   periodX: 2400, bobRate: 2400, accentEvery: 3600 },
  hover:      { ampY: 3.4, periodY: 1050, ampX: 1.6, periodX: 1700, bobRate: 525,  accentEvery: 2900 },
  serpentine: { ampY: 1.1, periodY: 900,  ampX: 3.2, periodX: 1800, bobRate: 900,  accentEvery: 3400 },
  inert:      { ampY: 1.0, periodY: 3200, ampX: 0,   periodX: 3200, bobRate: 3200, accentEvery: 2600 },
};

export function idleClassOf(speciesId) {
  return IDLE_CLASS[speciesId] || 'grounded';
}

// Deterministic per-species phase (0..1) so two battlers on screen —
// or two of the same species — never idle in sync. Hash, never RNG.
export function idlePhaseOf(speciesId) {
  let h = 0;
  const s = String(speciesId || '');
  for (let i = 0; i < s.length; i++) h = (Math.imul(h, 31) + s.charCodeAt(i)) | 0;
  return ((h >>> 0) % 1000) / 1000;
}
