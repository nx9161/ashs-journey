// ---------------- full deck views -------------------------------------------

const NAV_FULL = [
  ['overview', 'Overview'],
  ['players', 'Players'],
  ['system', 'System'],
  ['setup', 'Setup'],
];

async function viewOverview() {
  setNav(NAV_FULL, 'overview');
  h1('Overview', 'The game at a glance.');
  const { status, body } = await api('overview');
  if (status !== 200 || !body) { notice('Overview failed to load (HTTP ' + status + ').', 'error'); return; }
  const cards = el('div', 'cards');
  cards.appendChild(statCard('Players', String(body.users.total), 'accounts registered'));
  cards.appendChild(statCard('New · 7 days', String(body.users.signups7d), 'signups in the last week'));
  cards.appendChild(statCard('New · 30 days', String(body.users.signups30d), 'signups in the last month'));
  if (body.saves) {
    cards.appendChild(statCard('Cloud saves', String(body.saves.total), fmtBytes(body.saves.totalBytes) + ' stored'));
  }
  main.appendChild(cards);
  if (!body.saves && body.savesNote) {
    notice('Save totals are unavailable at this player count (aggregate limit reached). Applying migration 003 (see Setup) unlocks global save totals.');
  }
  main.appendChild(el('h2', null, 'Recent signups'));
  main.appendChild(table(['Username', 'Signed up'],
    (body.recentSignups || []).map((r) => [r.username, fmtDate(r.createdAt)])));
  main.appendChild(el('h2', null, 'Recent saves'));
  main.appendChild(table(['Player', 'Slot', 'Version', 'Size', 'Updated'],
    (body.recentSaves || []).map((r) => [r.username, 'Slot ' + r.slot, 'v' + r.version, fmtBytes(r.sizeBytes), fmtDate(r.updatedAt)])));
}

let playersState = { q: '', offset: 0, limit: 25, total: 0 };

async function viewPlayers() {
  setNav(NAV_FULL, 'players');
  h1('Players', 'Every registered account. Read-only — click a row for save slots.');
  const bar = el('div');
  const input = document.createElement('input');
  input.type = 'text';
  input.placeholder = 'Search by username…';
  input.value = playersState.q;
  const go = el('button', 'btn', 'Search');
  go.addEventListener('click', () => {
    playersState.q = input.value.trim();
    playersState.offset = 0;
    viewPlayers();
  });
  input.addEventListener('keydown', (e) => { if (e.key === 'Enter') go.click(); });
  bar.appendChild(input);
  bar.appendChild(document.createTextNode(' '));
  bar.appendChild(go);
  main.appendChild(bar);
  const holder = el('div');
  main.appendChild(holder);
  const { status, body } = await api('players', {
    q: playersState.q, limit: playersState.limit, offset: playersState.offset,
  });
  if (status !== 200 || !body) { holder.appendChild(el('p', null, 'Player list failed to load (HTTP ' + status + ').')); return; }
  playersState.total = body.total;
  holder.appendChild(table(['Username', 'Signed up', 'Last sign-in'],
    body.rows.map((r) => [r.username, fmtDate(r.createdAt), fmtDate(r.lastLogin)]),
    (cells) => {
      const row = body.rows.find((r) => r.username === cells[0]);
      if (row) viewPlayer(row.userId);
    }));
  const pager = el('div', 'pager');
  const prev = el('button', 'btn ghost', '← Prev');
  prev.disabled = playersState.offset === 0;
  prev.addEventListener('click', () => { playersState.offset = Math.max(0, playersState.offset - playersState.limit); viewPlayers(); });
  const next = el('button', 'btn ghost', 'Next →');
  next.disabled = playersState.offset + playersState.limit >= playersState.total;
  next.addEventListener('click', () => { playersState.offset += playersState.limit; viewPlayers(); });
  pager.appendChild(prev);
  pager.appendChild(el('span', 'mut small', 'Showing ' + (body.rows.length ? playersState.offset + 1 : 0) + '–' + (playersState.offset + body.rows.length) + ' of ' + body.total));
  pager.appendChild(next);
  holder.appendChild(pager);
}

async function viewPlayer(userId) {
  setNav(NAV_FULL, 'players');
  h1('Player', 'Account facts and save slots.');
  const { status, body } = await api('player', { userId });
  if (status !== 200 || !body) { notice('Player failed to load (HTTP ' + status + ').', 'error'); return; }
  const facts = el('div', 'cards');
  facts.appendChild(statCard('Username', body.username, 'account'));
  facts.appendChild(statCard('Signed up', fmtDate(body.createdAt), ''));
  facts.appendChild(statCard('Last sign-in', fmtDate(body.lastLogin), ''));
  main.appendChild(facts);
  main.appendChild(el('h2', null, 'Save slots'));
  if (!body.slots.length) {
    main.appendChild(el('p', 'mut', 'No cloud saves for this player.'));
    return;
  }
  main.appendChild(table(
    ['Slot', 'Version', 'Size', 'Playtime', 'Story beat', 'Badges', 'Updated'],
    body.slots.map((s) => ['Slot ' + s.slot, 'v' + s.version, fmtBytes(s.sizeBytes),
      Math.round(s.playtimeSec / 60) + ' min', String(s.storyBeat), String(s.badgeCount), fmtDate(s.updatedAt)]),
    (cells) => {
      const slot = body.slots.find((s) => 'Slot ' + s.slot === cells[0]);
      if (slot) viewSave(userId, slot.slot);
    }));
}

async function viewSave(userId, slot) {
  setNav(NAV_FULL, 'players');
  h1('Save inspector', 'Full payload for one slot. This view is audit-logged.');
  const { status, body } = await api('save', { userId, slot });
  if (status !== 200 || !body) { notice('Save failed to load (HTTP ' + status + ').', 'error'); return; }
  const facts = el('div', 'cards');
  facts.appendChild(statCard('Player', body.username, 'slot ' + body.slot));
  facts.appendChild(statCard('Version', 'v' + body.version, 'schema ' + body.schemaVersion));
  facts.appendChild(statCard('Size', fmtBytes(body.sizeBytes), 'payload'));
  facts.appendChild(statCard('Updated', fmtDate(body.updatedAt), 'server time'));
  main.appendChild(facts);
  const back = el('button', 'btn ghost', '← Back to player');
  back.addEventListener('click', () => viewPlayer(userId));
  main.appendChild(back);
  main.appendChild(el('h2', null, 'Payload'));
  const pre = el('pre', 'payload');
  pre.textContent = JSON.stringify(body.payload, null, 2);
  main.appendChild(pre);
}

async function viewSystem() {
  setNav(NAV_FULL, 'system');
  h1('System', 'Build, runtime and database health.');
  const { status, body } = await api('system');
  if (status !== 200 || !body) { notice('System info failed to load (HTTP ' + status + ').', 'error'); return; }
  main.appendChild(table(['Key', 'Value'], [
    ['API version', body.apiVersion],
    ['Node', body.node],
    ['Vercel environment', body.vercelEnv],
    ['Vercel region', body.vercelRegion],
    ['Git commit', body.gitCommitSha],
    ['Game data tables', body.tables && body.tables.ready ? 'ready · ' + body.tables.version : 'NOT ready'],
    ['Database', body.db.ok ? 'reachable · ' + body.db.latencyMs + ' ms' : 'NOT reachable'],
    ['Server time', fmtDate(body.time)],
  ]));
}

async function route(id) {
  if (id === 'overview') return viewOverview();
  if (id === 'players') return viewPlayers();
  if (id === 'system') return viewSystem();
  if (id === 'setup') {
    const { body } = await api('setup');
    if (body) return viewSetupReady(body);
  }
}

