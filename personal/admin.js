async function boot() {
  if (EDITION === 'personal') {
    // The personal project serves no functions; /api/health cannot answer.
    viewRemoteDeck();
    return;
  }
  let health = null;
  try {
    const res = await fetch('/api/health', { headers: { accept: 'application/json' } });
    health = await res.json();
  } catch { /* treated as unprovisioned */ }
  if (!health || health.authConfigured === false) { viewStage1(); return; }

  const { status, body } = await api('setup');
  if (status === 401) { viewSignIn(); return; }
  if (status === 403 && body && body.error === 'forbidden') { viewForbidden(); return; }
  if (status === 200 && body) {
    if (body.state === 'bootstrap') { viewSetupBootstrap(body); return; }
    viewOverview();
    return;
  }
  h1('Command Deck', 'Something went wrong loading the deck (HTTP ' + status + '). Try reloading.');
}

boot();
