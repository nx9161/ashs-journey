const PROBE_GUIDE = {
  databaseUrl: ['DATABASE_URL', 'Supabase pooler connection string for the app_role database user. Set in Vercel → Settings → Environment Variables.'],
  betterAuthSecret: ['BETTER_AUTH_SECRET', 'Present is all this dashboard can check — it cannot verify the secret’s strength. Use a long random value generated by Vercel or your password manager.'],
  betterAuthUrl: ['BETTER_AUTH_URL', 'The public origin of this site. Better Auth uses it for cookies and trusted origins.'],
  adminUsernames: ['ADMIN_USERNAMES', 'The dashboard allowlist. Use the exact username of the game account you actually play on. Warning: entries that are reserved game usernames (e.g. admin, owner, naman) can never match any account, because nobody can register them.'],
  adminEmails: ['ADMIN_EMAILS', 'In this game, account emails are synthetic (<username>@game.local). List your game username under ADMIN_USERNAMES instead — ADMIN_EMAILS only matches if you enter that exact synthetic address.'],
  cronSecret: ['CRON_SECRET', 'Used by the scheduled data-purge job.'],
};

function renderProbes(probes) {
  for (const [key, [name, hint]] of Object.entries(PROBE_GUIDE)) {
    const p = probes[key] || {};
    const box = el('div', 'probe');
    const line = el('div', 'name');
    const dotCls = !p.configured ? 'bad' : (key === 'databaseUrl' && p.ok === false ? 'warn' : 'ok');
    const dot = el('span', 'dot ' + dotCls);
    line.appendChild(dot);
    line.appendChild(document.createTextNode(name));
    const status = el('span', 'mut small', '  ' + (!p.configured
      ? 'not set'
      : key === 'databaseUrl'
        ? (p.ok ? 'set · database reachable' : 'set · database NOT reachable')
        : key === 'betterAuthUrl'
          ? (p.parseable ? 'set · valid URL' : 'set · not a valid URL')
          : 'set' + (typeof p.entries === 'number' ? ' · ' + p.entries + (p.entries === 1 ? ' entry' : ' entries') : '')));
    line.appendChild(status);
    box.appendChild(line);
    box.appendChild(el('div', 'hint', hint));
    main.appendChild(box);
  }
}

function renderManualChecks(checks) {
  main.appendChild(el('h2', null, 'Manual checks — only you can do these'));
  main.appendChild(el('p', 'lede', 'These live outside this website’s control, so the dashboard cannot verify them. Tick them off here as you confirm each one (ticks are stored only in this browser).'));
  for (const c of checks || []) {
    const row = el('label', 'check');
    const box = document.createElement('input');
    box.type = 'checkbox';
    box.checked = localStorage.getItem('deck.manual.' + c.id) === '1';
    box.addEventListener('change', () => {
      localStorage.setItem('deck.manual.' + c.id, box.checked ? '1' : '0');
    });
    row.appendChild(box);
    row.appendChild(el('span', null, c.instruction));
    main.appendChild(row);
  }
}

function step(n, text) {
  const d = el('div', 'step');
  d.appendChild(el('span', 'n', String(n)));
  d.appendChild(document.createTextNode(text));
  main.appendChild(d);
}

