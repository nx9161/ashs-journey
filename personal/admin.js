'use strict';

const EDITION = 'personal';
const PUBLIC_DECK_URL = 'https://ashs-journey-game-nx9161s-projects.vercel.app/admin';

const main = document.getElementById('main');
const nav = document.getElementById('nav');

function el(tag, cls, text) {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text != null) e.textContent = text;
  return e;
}
function clear(node) { while (node.firstChild) node.removeChild(node.firstChild); }
function h1(text, sub) {
  clear(main);
  main.appendChild(el('h1', null, text));
  if (sub) main.appendChild(el('p', 'lede', sub));
}
function notice(text, cls) {
  const d = el('div', cls || 'notice', text);
  main.appendChild(d);
  return d;
}
function fmtBytes(n) {
  if (typeof n !== 'number') return '—';
  if (n < 1024) return n + ' B';
  if (n < 1024 * 1024) return (n / 1024).toFixed(1) + ' KB';
  return (n / (1024 * 1024)).toFixed(2) + ' MB';
}
function fmtDate(v) {
  if (!v) return '—';
  const d = new Date(v);
  return Number.isNaN(d.getTime()) ? String(v) : d.toLocaleString();
}
async function api(action, params) {
  const qs = new URLSearchParams({ action, ...(params || {}) });
  const res = await fetch('/api/admin?' + qs.toString(), { headers: { accept: 'application/json' } });
  let body = null;
  try { body = await res.json(); } catch { /* non-JSON */ }
  return { status: res.status, body };
}
function table(headers, rows, onRow) {
  const t = el('table');
  const thead = el('thead');
  const trh = el('tr');
  for (const htxt of headers) trh.appendChild(el('th', null, htxt));
  thead.appendChild(trh);
  t.appendChild(thead);
  const tbody = el('tbody');
  for (const cells of rows) {
    const tr = el('tr', onRow ? 'clickable' : null);
    for (const c of cells) tr.appendChild(el('td', null, c == null ? '—' : String(c)));
    if (onRow) tr.addEventListener('click', () => onRow(cells));
    tbody.appendChild(tr);
  }
  t.appendChild(tbody);
  return t;
}
function statCard(k, v, s) {
  const c = el('div', 'card');
  c.appendChild(el('div', 'k', k));
  c.appendChild(el('div', 'v', v));
  if (s) c.appendChild(el('div', 's', s));
  return c;
}
function setNav(items, active) {
  clear(nav);
  for (const [id, label] of items) {
    const b = el('button', id === active ? 'on' : null, label);
    b.addEventListener('click', () => route(id));
    nav.appendChild(b);
  }
}

